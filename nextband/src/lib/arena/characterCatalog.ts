export function getCharacterBySeed(seed?: number | string): CharacterAvatar {
  if (seed === undefined || seed === null) {
    return CHARACTER_AVATARS[0];
  }
  
  if (typeof seed === 'number') {
    const idx = Math.abs(seed) % CHARACTER_AVATARS.length;
    return CHARACTER_AVATARS[idx];
  }

  // Nếu là chuỗi số
  const parsed = parseInt(seed, 10);
  if (!isNaN(parsed)) {
    const idx = Math.abs(parsed) % CHARACTER_AVATARS.length;
    return CHARACTER_AVATARS[idx];
  }

  // Hash chuỗi tên để chọn avatar cố định
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % CHARACTER_AVATARS.length;
  return CHARACTER_AVATARS[idx];
}
