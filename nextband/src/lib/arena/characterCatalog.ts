export function getCharacterBySeed(seed: string | number): CharacterAvatar {
  let num = 0;
  if (typeof seed === 'number') {
    num = Math.abs(seed);
  } else if (typeof seed === 'string') {
    for (let i = 0; i < seed.length; i++) {
      num = (num << 5) - num + seed.charCodeAt(i);
      num |= 0;
    }
    num = Math.abs(num);
  }
  const idx = num % CHARACTER_AVATARS.length;
  return CHARACTER_AVATARS[idx];
}
