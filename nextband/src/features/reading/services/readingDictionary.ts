export function isContentWord(word: string): boolean {
  const clean = word.toLowerCase().replace(/[^a-z0-9-]/g, "").trim();
  if (!clean || clean.length < 2) return false;
  if (/^\d+$/.test(clean)) return false;
  return !FUNCTION_WORDS.has(clean);
}

